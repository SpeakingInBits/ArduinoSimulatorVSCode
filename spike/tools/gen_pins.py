"""Generate the simulator's SAMD21G18A pin table from Adafruit's samd-peripherals data."""
import re
import sys

src, out_c, out_h = sys.argv[1:4]
text = open(src, encoding="utf-8").read()
# Pins present on the 48-pin SAMD21G18A package.
G18 = [f"PA{i:02d}" for i in range(26)] + ["PA27", "PA28", "PA30", "PA31"]
G18 += ["PB02", "PB03", "PB08", "PB09", "PB10", "PB11", "PB22", "PB23"]
IGNORED = {"PA00", "PA01", "PA24", "PA25"}  # Crystal and USB, per the Metro M0 board file.

rows = []
for m in re.finditer(r"^PIN\((P[AB]\d\d),(.*?)\);", text, re.M | re.S):
    name, body = m.group(1), m.group(2)
    if name not in G18 or name in IGNORED:
        continue
    body = re.sub(r"^\s*#.*$", "", body, flags=re.M)
    adc = re.search(r"ADC_INPUT\((\d+)\)", body)
    sercoms = re.findall(r"(?<![A-Z_])SERCOM\((\d+),\s*(\d+)\)", body)
    has_timer = bool(re.search(r"\bTCC?\(", body))
    number = int(name[2:]) + (32 if name[1] == "B" else 0)
    s = (sercoms + [("255", "255")] * 2)[:2]
    rows.append((name, number, int(adc.group(1)) if adc else 255, int(has_timer), s))

with open(out_h, "w", newline="\n") as f:
    f.write("// Generated by spike/tools/gen_pins.py. Do not edit.\n#pragma once\n\n")
    for r in rows:
        f.write(f"extern const mcu_pin_obj_t pin_{r[0]};\n")
    f.write("\n#define SIM_FOR_EACH_PIN(X) \\\n")
    f.write(" \\\n".join(f"    X({r[0]})" for r in rows) + "\n")
with open(out_c, "w", newline="\n") as f:
    f.write('// Generated by spike/tools/gen_pins.py. Do not edit.\n#include "shared-bindings/microcontroller/Pin.h"\n\n')
    for name, number, adc, timer, s in rows:
        f.write(f"const mcu_pin_obj_t pin_{name} = {{ {{ &mcu_pin_type }}, {number}, {adc}, {timer}, "
                f"{{ {{ {s[0][0]}, {s[0][1]} }}, {{ {s[1][0]}, {s[1][1]} }} }} }};\n")
print(len(rows), "pins;", sum(1 for r in rows if r[2] != 255), "ADC;", sum(r[3] for r in rows), "PWM")
for n in ("PA02", "PA17", "PB08", "PA22", "PA23", "PA30"):
    print([r for r in rows if r[0] == n])
