"""Generate the simulator's SAMD21G18A pin table from Adafruit's samd-peripherals data.

Usage: gen_pins.py <samd/samd21/pins.c> <out pins.c> <out pins.h>
Input: https://raw.githubusercontent.com/adafruit/samd-peripherals/main/samd/samd21/pins.c

The struct fields keep the names in that file, and each slot keeps its position, because the real
drivers read them by position: slot 0 is peripheral mux C (or E for timers), slot 1 is mux D (or F).
"""
import re
import sys

src, out_c, out_h = sys.argv[1:4]
text = open(src, encoding="utf-8").read()

# Pins present on the 48-pin SAMD21G18A package.
G18 = [f"PA{i:02d}" for i in range(26)] + ["PA27", "PA28", "PA30", "PA31"]
G18 += ["PB02", "PB03", "PB08", "PB09", "PB10", "PB11", "PB22", "PB23"]
IGNORED = {"PA00", "PA01", "PA24", "PA25"}  # Crystal and USB, per the Metro M0 board file.

# The input selects per-chip data with #ifdef. The G18A has SERCOM4 and SERCOM5 but only TC3-TC5,
# and PA02_NO_TOUCH is only defined for the Circuit Playground Express.
DEFINED = {"SERCOM4", "SERCOM5"}
NO_SERCOM = (0x3F, 0)
NO_TIMER = (0xF, 0, 0)


def resolve_ifdefs(body):
    """Keeps only the lines that the C preprocessor would keep for this chip."""
    kept, active = [], [True]
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("#ifdef"):
            active.append(active[-1] and stripped.split()[1] in DEFINED)
        elif stripped.startswith("#else"):
            active[-1] = active[-2] and not active[-1]
        elif stripped.startswith("#endif"):
            active.pop()
        elif not stripped.startswith("#") and active[-1]:
            kept.append(line)
    return "\n".join(kept)


def split_args(body):
    args, depth, current = [], 0, ""
    for char in body:
        if char == "," and depth == 0:
            args.append(current.strip())
            current = ""
            continue
        depth += (char == "(") - (char == ")")
        current += char
    args.append(current.strip())
    return args


def sercom(arg):
    match = re.fullmatch(r"SERCOM\((\d+),\s*(\d+)\)", arg)
    return (int(match[1]), int(match[2])) if match else NO_SERCOM


def timer(arg):
    match = re.fullmatch(r"(TCC?)\((\d+),\s*(\d+)\)", arg)
    if not match:
        return NO_TIMER
    is_tc = match[1] == "TC"
    # The TC() macro stores the index minus 3, so that TC3 is entry 0 of tc_insts on a SAMD21.
    return (int(match[2]) - (3 if is_tc else 0), int(is_tc), int(match[3]))


rows = []
for m in re.finditer(r"^PIN\((P[AB]\d\d),(.*?)\);", text, re.M | re.S):
    name = m.group(1)
    if name not in G18 or name in IGNORED:
        continue
    extint, adc, touch, sercom0, sercom1, timer0, timer1 = split_args(resolve_ifdefs(m.group(2)))
    extint_match = re.fullmatch(r"EXTINT_CHANNEL\((\d+)\)", extint)
    adc_match = re.fullmatch(r"ADC_INPUT\((\d+)\)", adc)
    touch_match = re.fullmatch(r"TOUCH\((\d+)\)", touch)
    rows.append({
        "name": name,
        "number": int(name[2:]) + (32 if name[1] == "B" else 0),
        "extint": int(extint_match[1]) if extint_match else None,
        "adc": int(adc_match[1]) if adc_match else 255,
        "touch": int(touch_match[1]) if touch_match else None,
        "sercom": (sercom(sercom0), sercom(sercom1)),
        "timer": (timer(timer0), timer(timer1)),
    })

with open(out_h, "w", newline="\n") as f:
    f.write("// Generated by firmware/tools/gen_pins.py. Do not edit.\n#pragma once\n\n")
    for r in rows:
        f.write(f"extern const mcu_pin_obj_t pin_{r['name']};\n")
    f.write("\n#define SIM_FOR_EACH_PIN(X) \\\n")
    f.write(" \\\n".join(f"    X({r['name']})" for r in rows) + "\n")

with open(out_c, "w", newline="\n") as f:
    f.write("// Generated by firmware/tools/gen_pins.py. Do not edit.\n")
    f.write('#include "shared-bindings/microcontroller/Pin.h"\n\n')
    for r in rows:
        extint, touch = r["extint"], r["touch"]
        sercoms = ", ".join(f"{{ {s[0]}, {s[1]} }}" for s in r["sercom"])
        timers = ", ".join(f"{{ {t[0]}, {t[1]}, {t[2]} }}" for t in r["timer"])
        f.write(f"const mcu_pin_obj_t pin_{r['name']} = {{ {{ &mcu_pin_type }}, {r['number']}, "
                f"{int(extint is not None)}, {extint or 0}, {int(touch is not None)}, {touch or 0}, "
                f"{r['adc']}, {{ {timers} }}, {{ {sercoms} }} }};\n")

usable = [r for r in rows if r["timer"][0][0] != 0xF or r["timer"][1][0] != 0xF]
print(len(rows), "pins;", sum(r["adc"] != 255 for r in rows), "ADC;", len(usable), "PWM;",
      sum(r["extint"] is not None for r in rows), "EXTINT;", sum(r["touch"] is not None for r in rows), "touch")
